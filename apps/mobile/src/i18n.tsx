export type TranslationKey = keyof typeof zh

interface I18nValue {
  language: Language
  locale: string
  setLanguage: (language: Language) => void
  t: (key: TranslationKey, values?: Record<string, string | number>) => string
}

const LanguageContext = createContext<I18nValue | null>(null)

function format(template: string, values?: Record<string, string | number>): string {
  if (values === undefined) return template
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key as keyof typeof values]) : match)
}

export function I18nProvider({ children }: { children: React.ReactNode }): React.JSX.Element {
  const [language, setLanguageState] = useState<Language>('zh')

  useEffect(() => {
    void AsyncStorage.getItem(DEFAULT_LANGUAGE_VERSION_KEY)
      .then(async initialized => {
        // The first release defaulted to the device language in some builds.
        // Normalize existing installs once; future explicit choices persist.
        if (initialized !== '1') {
          await AsyncStorage.setItem(STORAGE_KEY, 'zh')
          await AsyncStorage.setItem(DEFAULT_LANGUAGE_VERSION_KEY, '1')
          setLanguageState('zh')
          return
        }
        const value = await AsyncStorage.getItem(STORAGE_KEY)
        if (value === 'system' || value === 'zh' || value === 'en') setLanguageState(value)
      })
      .catch(() => undefined)
  }, [])

  const setLanguage = useCallback((next: Language) => {
    setLanguageState(next)
    void AsyncStorage.setItem(STORAGE_KEY, next).catch(() => undefined)
  }, [])

  const dictionaryRef = useRef<Record<TranslationKey, string>>(zh)

  const t = useCallback((key: TranslationKey, values?: Record<string, string | number>): string =>
    format(dictionaryRef.current[key] ?? zh[key], values), [])

  const value = useMemo<I18nValue>(() => {
    const systemLocale = (NativeModules.I18nManager as { localeIdentifier?: string } | undefined)?.localeIdentifier
    const resolved = language === 'system'
      ? (systemLocale?.toLowerCase().startsWith('zh') ? 'zh' : 'en')
      : language
    const dictionary = resolved === 'zh' ? zh : { ...zh, ...en }
    dictionaryRef.current = dictionary
    return { language, locale: resolved === 'zh' ? 'zh-CN' : 'en-US', setLanguage, t }
  }, [language, setLanguage, t])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useI18n(): I18nValue {
  const value = useContext(LanguageContext)
  if (value === null) throw new Error('useI18n must be used within I18nProvider')
  return value
}
